# 5. End-to-End Simulator & Assessment Integration
# =============================================================================

def test_end_to_end_firmware_telemetry_integration():
    """Verify live firmware telemetry flows cleanly through Simulator and Hazard Engine."""
    rec = get_serial_receiver()
    sample = '{"device_id":"safeedge-esp32-01","temperature_c":36.5,"humidity_pct":75.0,"gas_raw":1450,"noise_raw":1920}'
    rec.feed_mock_message(sample, set_connected=True)

    sim = IoTHardwareSimulator()
    telemetry = sim.read_sensors(data_source="live_esp32")

    assert telemetry["data_source"] == "live_esp32"
    assert telemetry["is_stale"] is False
    assert telemetry["readings"] is not None

    readings = telemetry["readings"]
    # Temperature at 36.5 °C triggers WARNING (> 35.0 °C)
    assert readings["temperature"]["value"] == 36.5
    assert readings["temperature"]["status"] == "WARNING"

    # Gas and Noise are raw uncalibrated ADC (never classified as SAFE)
    assert readings["gas"]["unit"] == "ADC"
    assert readings["gas"]["status"] == "UNCALIBRATED"
    assert readings["gas"]["is_uncalibrated"] is True

    assert readings["noise"]["unit"] == "ADC"
    assert readings["noise"]["status"] == "UNCALIBRATED"
    assert readings["noise"]["is_uncalibrated"] is True

    # Assessment engine test
    meta = {
        "temperature": {"display_name": "Temperature", "unit": "°C", "thresholds": {"safe_min": 15, "safe_max": 30, "warning_min": 5, "warning_max": 38}},
        "humidity": {"display_name": "Humidity", "unit": "%", "thresholds": {"safe_min": 30, "safe_max": 60, "warning_min": 20, "warning_max": 80}},
        "gas": {"display_name": "Gas Concentration", "unit": "ppm"},
        "noise": {"display_name": "Noise Level", "unit": "dB"},
    }
    assessment = HazardAssessmentEngine.assess_esp32_reading(rec.get_latest_reading(), meta)
    assert assessment.data_source == "live_esp32"
    assert assessment.device_id == "safeedge-esp32-01"
    assert assessment.uncalibrated_count == 2
    assert assessment.overall_status in (HazardStatus.WARNING, HazardStatus.DANGER)


