def test_firmware_pin_assignments_use_safe_adc1():
    """Verify analog sensors are assigned to ADC1 pins (GPIO 32-39) safe for Wi-Fi."""
    cfg_text = (FIRMWARE_DIR / "config.h").read_text(encoding="utf-8")

    # MQ-135 on GPIO 34 (ADC1_CH6)
    assert "#define PIN_MQ135_ADC           34" in cfg_text
    # MAX9814 on GPIO 35 (ADC1_CH7)
    assert "#define PIN_MIC_ADC             35" in cfg_text
    # DHT22 on GPIO 4
    assert "#define PIN_DHT                 4" in cfg_text


def test_firmware_no_hardcoded_secrets():
    """Verify firmware source files do not contain real Wi-Fi passwords or API keys."""
    for f in [FIRMWARE_DIR / "config.h", FIRMWARE_DIR / "esp32_sensor_node.ino"]:
        text = f.read_text(encoding="utf-8").lower()
        assert "password" not in text or "placeholder" in text
        assert "api_key" not in text or "placeholder" in text

