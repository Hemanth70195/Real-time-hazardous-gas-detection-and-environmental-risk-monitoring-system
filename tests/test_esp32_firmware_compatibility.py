# 4. Boundary Values Tests (12-bit ADC & Physical Ranges)
# =============================================================================

def test_boundary_values(receiver):
    """Verify boundary conditions for 12-bit ADC (0 and 4095) and particulate limits."""
    # 0 ADC minimum
    payload_min = '{"device_id":"safeedge-esp32-01","temperature_c":-10.0,"humidity_pct":0.0,"gas_raw":0,"pm1_0":0.0,"pm2_5":0.0,"pm10":0.0,"noise_raw":0}'
    p_min = receiver.process_incoming_line(payload_min)
    assert p_min is not None
    assert p_min.gas_raw == 0.0
    assert p_min.noise_raw == 0.0
    assert p_min.temperature_c == -10.0

    # 4095 ADC maximum (full scale on 12-bit ADC)
    payload_max = '{"device_id":"safeedge-esp32-01","temperature_c":55.0,"humidity_pct":100.0,"gas_raw":4095,"pm1_0":500.0,"pm2_5":500.0,"pm10":500.0,"noise_raw":4095}'
    p_max = receiver.process_incoming_line(payload_max)
    assert p_max is not None
    assert p_max.gas_raw == 4095.0
    assert p_max.noise_raw == 4095.0


