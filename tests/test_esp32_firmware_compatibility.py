def test_startup_diagnostic_lines_ignored(receiver):
    """Verify firmware diagnostic comment lines (// ...) do not corrupt the receiver."""
    diag_lines = [
        "// SafeEdge HazardGuard ESP32 Sensor Node Initializing...",
        "// Device ID: safeedge-esp32-01",
        "// DHT22 initialized on GPIO 4",
        "// PMS5003 UART2 initialized on RX=GPIO 16, TX=GPIO 17",
        "// Initialization complete. Streaming telemetry...",
    ]
    for line in diag_lines:
        res = receiver.process_incoming_line(line)
        assert res is None  # Safely rejected without crashing

    # A subsequent real JSON packet parses immediately
    real_line = '{"device_id":"safeedge-esp32-01","temperature_c":24.5,"humidity_pct":48.0,"gas_raw":1200,"pm1_0":10.0,"pm2_5":20.0,"pm10":30.0,"noise_raw":1600}'
    parsed = receiver.process_incoming_line(real_line)
    assert parsed is not None
    assert parsed.temperature_c == 24.5


